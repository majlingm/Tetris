  getNewPiece() {
    this.rotation = 0;
    this.activePieces.push(Math.floor(Math.random() * this.pieces.length));

    return this.pieces[this.activePieces[this.activePieces.length - 1]][0];
  }

  getNextRotation() {
    const currentPieceIndex = this.activePieces[this.activePieces.length - 2];

    if (this.rotation < (this.pieces[currentPieceIndex].length - 1)) {
      this.rotation++;
    } else {
      this.rotation = 0;
    }

    return this.pieces[currentPieceIndex][this.rotation];
  }

  // Return the piece to be expected next time you call getNextRotation
  seeNextInRotation() {
    const currentPieceIndex = this.activePieces[this.activePieces.length - 2];
    let r;

    if (this.rotation < (this.pieces[currentPieceIndex].length - 1)) {
      r = this.rotation + 1;
    } else {
      r = 0;
    }

    return this.pieces[currentPieceIndex][r];
  }
